/// Разовое обновление контента уже созданных упражнений: раньше шаг «Внимания»
/// предлагал просто «постепенно увеличивай время» без конкретики — теперь это чёткая
/// прогрессия по секундам. Не создаёт новых записей и не трогает историю тренировок —
/// только обновляет текст шагов и метаданные у существующего упражнения, если они
/// ещё старые. Затрагивает только встроенные упражнения (isCustom == false) — свои
/// созданные пользователем упражнения этот код не трогает, у них title не совпадёт
/// ни с одним seed-упражнением.
func updateSeedExercisesIfNeeded(context: ModelContext) {
    // Один запрос всех упражнений и поиск по словарю в памяти вместо
    // отдельного fetch-запроса на каждое из 15 упражнений при каждом запуске.
    guard let existingExercises = try? context.fetch(FetchDescriptor<Exercise>()) else { return }
    let existingByTitle = Dictionary(uniqueKeysWithValues: existingExercises.map { ($0.title, $0) })

    for data in seedExerciseData {
        guard let exercise = existingByTitle[data.title] else { continue }
        if exercise.steps != data.steps {
            exercise.steps = data.steps
        }
        if exercise.exerciseDescription != data.description {
            exercise.exerciseDescription = data.description
        }
        if exercise.audience != data.audience {
            exercise.audience = data.audience
        }
    }
}
