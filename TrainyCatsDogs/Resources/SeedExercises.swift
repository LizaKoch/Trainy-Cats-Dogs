/// Наполняет базу стартовой библиотекой упражнений при первом запуске
/// (если упражнений ещё нет). Дальше пользователь может ходить в каталог —
/// упражнения уже на месте.
func seedExercisesIfNeeded(context: ModelContext) {
    let descriptor = FetchDescriptor<Exercise>()
    let existingCount = (try? context.fetchCount(descriptor)) ?? 0
    guard existingCount == 0 else { return }

    for data in seedExerciseData {
        let exercise = Exercise(
            title: data.title,
            exerciseDescription: data.description,
            steps: data.steps,
            category: data.category,
            difficulty: data.difficulty,
            audience: data.audience
        )
        context.insert(exercise)
    }
}

